type Group = (typeof STAFF_TEXT_GROUPS)[number]
export type StaffTexts = { [G in Group as G['key']]: Record<G['fields'][number][0], string> }

export const DEFAULT_STAFF_TEXTS = Object.fromEntries(
  STAFF_TEXT_GROUPS.map((g) => [g.key, Object.fromEntries(g.fields.map(([k, , d]) => [k, d]))]),
) as StaffTexts

/** Key of a built-in page's name in the "Page visibility" tab: '/' → 'pRoot', '/aurix/sign-in' → 'pAurixSignIn' (note: 'n…'). */
export function visibilityPageKey(route: string): string {
  return 'p' + (route === '/' ? 'Root' : route.split(/[/-]/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join(''))
}

/** Section names in the "Page visibility" screen, by their internal group id. */
